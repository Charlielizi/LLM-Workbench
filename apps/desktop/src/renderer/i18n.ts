export function translate(
  locale: LocaleMode,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const dictionary = resolveLocale(locale) === "zh-CN" ? zhCN : enUS;
  let value: string = dictionary[key];
  for (const [name, replacement] of Object.entries(params ?? {})) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function useI18n(): {
  locale: "zh-CN" | "en-US";
  t: (key: TranslationKey, params?: Record<string, string | number>) => string;
} {
  const localeMode = useSettingsStore((state) => state.locale);
  const locale = resolveLocale(localeMode);
  const t = useCallback(
    (key: TranslationKey, params?: Record<string, string | number>) =>
      translate(localeMode, key, params),
    [localeMode],
  );
  return { locale, t };
}
